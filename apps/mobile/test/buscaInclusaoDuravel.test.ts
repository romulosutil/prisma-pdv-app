import React from 'react';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { beforeEach, afterEach, it, expect, vi } from 'vitest';
const m = vi.hoisted(() => ({ adicionar: vi.fn(), back: vi.fn(), produto: { id: 'p', nome: 'Arroz', unidade: 'un', precoCentavos: 1000 } as any }));
vi.mock('expo-router', () => ({ useRouter: () => ({ back: m.back, dismissTo: vi.fn(), push: vi.fn() }) }));
vi.mock('react-native', async () => { const R = await import('react'); return { View: 'view', TextInput: 'input', StyleSheet: { create: (s: any) => s }, FlatList: (p: any) => R.createElement('lista', p, p.ListHeaderComponent, ...p.data.map((item: any, index: number) => R.createElement(R.Fragment, { key: index }, p.renderItem({ item, index })))) }; });
vi.mock('@/tema', () => ({ cores: {}, raio: {}, texto: { corpoL: {} } }));
vi.mock('@/componentes/TelaBase', () => ({ TelaBase: ({ children }: any) => children }));
vi.mock('@/componentes/Botao', () => ({ Botao: 'botao' }));
vi.mock('@/componentes/BotaoIcone', () => ({ BotaoIcone: 'iconebotao' }));
vi.mock('@/componentes/Icone', () => ({ Icone: 'icone' }));
vi.mock('@/componentes/Ilustra', () => ({ Ilustra: 'ilustra' }));
vi.mock('@/componentes/Dinheiro', () => ({ Dinheiro: 'dinheiro' }));
vi.mock('@/componentes/Texto', () => ({ Texto: 'texto' }));
vi.mock('@/componentes/LinhaLista', () => ({ LinhaLista: 'linha' }));
vi.mock('@/componentes/Toast', () => ({ useToast: () => ({ mostrar: vi.fn() }) }));
vi.mock('@/dados/hooks', () => ({ useProdutos: () => ({ produtos: [m.produto], buscarPorNome: () => [m.produto] }) }));
vi.mock('@/telas/vender/useAdicionar', () => ({ useAdicionar: () => m.adicionar }));
vi.mock('@/telas/vender/FolhaPeso', () => ({ FolhaPeso: 'peso' }));
vi.mock('@/telas/vender/FolhaNaoEncontrado', () => ({ FolhaNaoEncontrado: () => null }));
import { TelaBusca } from '@/telas/vender/TelaBusca';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
let r: ReactTestRenderer;
beforeEach(() => { m.back.mockReset(); m.adicionar.mockReset(); m.produto.unidade = 'un'; });
afterEach(async () => { if (r) await act(async () => r.unmount()); });
const linha = () => r.root.findAll(n => n.type === 'linha' as any)[0]!;
it('mantém busca quando gravação falha e só navega após confirmação, recusando toques concorrentes', async () => {
  let resolver!: (v: boolean) => void;
  m.adicionar.mockImplementationOnce(() => new Promise<boolean>(r => { resolver = r; }));
  await act(async () => { r = create(React.createElement(TelaBusca)); });
  let voo: Promise<void>;
  await act(async () => { voo = linha().props.onPress(); void linha().props.onPress(); });
  expect(m.adicionar).toHaveBeenCalledOnce(); expect(m.back).not.toHaveBeenCalled();
  await act(async () => { resolver(false); await voo; }); expect(m.back).not.toHaveBeenCalled();
  m.adicionar.mockResolvedValueOnce(true);
  await act(async () => linha().props.onPress()); expect(m.back).toHaveBeenCalledOnce();
});
it('peso e formulário de busca permanecem acessíveis após falha de gravação', async () => {
  m.produto.unidade = 'kg'; m.adicionar.mockResolvedValue(false);
  await act(async () => { r = create(React.createElement(TelaBusca)); });
  await act(async () => linha().props.onPress());
  const peso = () => r.root.findByType('peso' as any);
  await act(async () => peso().props.onConfirmar(250));
  expect(peso().props.produto).toBe(m.produto); expect(m.back).not.toHaveBeenCalled();
  expect(r.root.findByType('lista' as any).findByType('input' as any)).toBeTruthy();
});
